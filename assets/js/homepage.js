    overlay.addEventListener('click', () => closeSidebar(false));
    sidebar.querySelectorAll('a').forEach((link) => link.addEventListener('click', () => closeSidebar(false)));
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape' && sidebar.classList.contains('is-open')) closeSidebar();
      if (event.key === 'Tab' && sidebar.classList.contains('is-open')) {
        const controls = [...sidebar.querySelectorAll('a[href], button:not([disabled])')];
        const first = controls[0];
        const last = controls.at(-1);
        if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
        else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
      }
    });

